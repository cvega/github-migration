/**
 * Generates the module lists that discover GitLab profile metrics. Every metric
 * is three files that share one stem: `<stem>.metric.ts` and `<stem>.fixture.ts`
 * under `src/lib/source/gitlab-metrics/`, and `<stem>.collector.ts` under
 * `src/lib/server/source/gitlab/metrics/`. The lists contain no hand-written
 * entries, so metric changes add files and the generated output follows.
 *
 * Bun runs the analysis worker, scripts and tests straight from source, where
 * `import.meta.glob` is unavailable, so discovery is generated and checked
 * (`bun scripts/packaging/generate-gitlab-metrics.ts --check`) instead.
 */
const CLIENT_DIRECTORY = "src/lib/source/gitlab-metrics";
const SERVER_DIRECTORY = "src/lib/server/source/gitlab/metrics";
const HEADER = "// Generated by scripts/packaging/generate-gitlab-metrics.ts. Do not edit.\n";

async function stems(directory: string, suffix: string): Promise<string[]> {
  const found: string[] = [];
  for await (const path of new Bun.Glob(`*.${suffix}.ts`).scan({
    cwd: directory,
    onlyFiles: true,
  })) {
    found.push(path.slice(0, -`.${suffix}.ts`.length));
  }
  return found.sort();
}

function identifier(stem: string, suffix: string): string {
  const [first = "", ...rest] = stem.split("-");
  const words = [first, ...rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1))];
  return `${words.join("")}${suffix.charAt(0).toUpperCase()}${suffix.slice(1)}`;
}

/** Import lines in the path order Biome's import organizer enforces. */
function imports(stems: string[], suffixes: string[]): string {
  return stems
    .flatMap((stem) => suffixes.map((suffix) => ({ stem, suffix, path: `./${stem}.${suffix}` })))
    .sort((left, right) => (left.path < right.path ? -1 : 1))
    .map(({ stem, suffix, path }) => `import ${identifier(stem, suffix)} from "${path}";`)
    .join("\n");
}

function list(names: string[], suffix: string): string {
  return names.map((stem) => `  ${identifier(stem, suffix)},`).join("\n");
}

export function generateGitLabMetricModules(inputs: {
  metrics: string[];
  fixtures: string[];
  collectors: string[];
}): Record<string, string> {
  const problems: string[] = [];
  for (const [label, other] of [
    ["fixture", inputs.fixtures],
    ["collector", inputs.collectors],
  ] as const) {
    for (const stem of inputs.metrics) {
      if (!other.includes(stem)) problems.push(`${stem}: missing ${label}`);
    }
    for (const stem of other) {
      if (!inputs.metrics.includes(stem)) problems.push(`${stem}: ${label} has no metric module`);
    }
  }
  if (problems.length > 0) {
    throw new Error(`GitLab metric files must share stems:\n  ${problems.join("\n  ")}`);
  }
  const { metrics } = inputs;
  return {
    [`${CLIENT_DIRECTORY}/modules.generated.ts`]: `${HEADER}
${imports(metrics, ["metric"])}

export const GITLAB_METRIC_DESCRIPTORS = [
${list(metrics, "metric")}
] as const;
`,
    [`${CLIENT_DIRECTORY}/fixtures.generated.ts`]: `${HEADER}
${imports(metrics, ["fixture", "metric"])}

/** One valid stored metric per registered key. */
export const GITLAB_METRIC_FIXTURES = {
${metrics
  .map((stem) => `  [${identifier(stem, "metric")}.key]: ${identifier(stem, "fixture")},`)
  .join("\n")}
} as const;
`,
    [`${SERVER_DIRECTORY}/collectors.generated.ts`]: `${HEADER}
${imports(metrics, ["collector"])}

export const GITLAB_METRIC_COLLECTORS = [
${list(metrics, "collector")}
] as const;
`,
  };
}

if (import.meta.main) {
  const outputs = generateGitLabMetricModules({
    metrics: await stems(CLIENT_DIRECTORY, "metric"),
    fixtures: await stems(CLIENT_DIRECTORY, "fixture"),
    collectors: await stems(SERVER_DIRECTORY, "collector"),
  });
  let stale = false;
  for (const [path, output] of Object.entries(outputs)) {
    if (process.argv.includes("--check")) {
      const existing = (await Bun.file(path).exists()) ? await Bun.file(path).text() : "";
      if (existing !== output) {
        console.error(`[gitlab-metrics] ${path} is stale`);
        stale = true;
      }
    } else {
      await Bun.write(path, output);
    }
  }
  if (stale) {
    console.error("[gitlab-metrics] run bun scripts/packaging/generate-gitlab-metrics.ts");
    process.exit(1);
  }
  console.log(
    `[gitlab-metrics] ${process.argv.includes("--check") ? "generated lists are current" : "generated lists"} (${Object.keys(outputs).length} files)`,
  );
}
