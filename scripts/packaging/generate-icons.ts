import octicons, { type IconName } from "@primer/octicons";

const OUTPUT = "src/lib/icons.generated.ts";
const SOURCE_GLOB = new Bun.Glob("**/*.{svelte,ts}");
const ICON_LITERAL = /(["'])([a-z][a-z0-9-]*)\1/g;

async function usedIconNames(): Promise<IconName[]> {
  const available = new Set(Object.keys(octicons) as IconName[]);
  const used = new Set<IconName>();
  for await (const path of SOURCE_GLOB.scan({ cwd: "src", onlyFiles: true })) {
    if (path === "lib/icons.generated.ts") continue;
    const source = await Bun.file(`src/${path}`).text();
    for (const match of source.matchAll(ICON_LITERAL)) {
      const candidate = match[2] as IconName;
      if (available.has(candidate)) used.add(candidate);
    }
  }
  return [...used].sort();
}

function heightData(name: IconName, size: 16 | 24) {
  const icon = octicons[name];
  const height = icon.heights[size] ?? icon.heights[16] ?? Object.values(icon.heights)[0];
  if (!height) throw new Error(`Octicon '${name}' has no renderable height`);
  return {
    width: height.options.width,
    height: height.options.height,
    paths: parsePaths(name, height.path),
  };
}

function parsePaths(name: IconName, markup: string) {
  const paths: Array<{
    d: string;
    fill: string | null;
    fillRule: string | null;
    clipRule: string | null;
  }> = [];
  const elementPattern = /<path\s+([^>]+)><\/path>/g;
  for (const element of markup.matchAll(elementPattern)) {
    const attributes = Object.fromEntries(
      [...(element[1] ?? "").matchAll(/([a-z-]+)="([^"]*)"/g)].map((match) => [match[1], match[2]]),
    );
    const unknown = Object.keys(attributes).filter(
      (attribute) => !["d", "fill", "fill-rule", "clip-rule"].includes(attribute),
    );
    if (!attributes.d || unknown.length > 0) {
      throw new Error(`Octicon '${name}' contains unsupported SVG path data`);
    }
    paths.push({
      d: attributes.d,
      fill: attributes.fill ?? null,
      fillRule: attributes["fill-rule"] ?? null,
      clipRule: attributes["clip-rule"] ?? null,
    });
  }
  if (paths.length === 0 || markup.replace(elementPattern, "").trim()) {
    throw new Error(`Octicon '${name}' contains unsupported SVG elements`);
  }
  return paths;
}

function generate(names: IconName[]): string {
  const entries = names
    .map((name) => {
      const sizes = { 16: heightData(name, 16), 24: heightData(name, 24) };
      return `  ${JSON.stringify(name)}: ${JSON.stringify(sizes)},`;
    })
    .join("\n");
  return `// Generated by scripts/packaging/generate-icons.ts. Do not edit.\nexport const ICONS = {\n${entries}\n} as const;\n\nexport type UsedIconName = keyof typeof ICONS;\n`;
}

const output = generate(await usedIconNames());
if (process.argv.includes("--check")) {
  const existing = await Bun.file(OUTPUT).text();
  if (existing !== output) {
    console.error(`[icons] ${OUTPUT} is stale; run bun scripts/packaging/generate-icons.ts`);
    process.exit(1);
  }
  console.log(`[icons] ${OUTPUT} is current`);
} else {
  await Bun.write(OUTPUT, output);
  console.log(`[icons] generated ${OUTPUT}`);
}
